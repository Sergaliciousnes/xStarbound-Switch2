// Standalone host test: no Horizon, SDL or game assets required.
#include "StarSwitch2Controls.hpp"
#include <cstdio>
#include <stdexcept>

using Controls = Star::Switch2Controls;
void require(bool passed, char const* message) {
  if (!passed) throw std::runtime_error(message);
}

int main() {
  try {
    Controls controls;
    Controls::Sample input;
    input.connected = true;
    auto state = controls.update(input, 1.0f / 60, 1280, 720);
    require(!state.left && !state.right && !state.up && !state.down && !state.primary, "Neutral input");
    input.leftX = -0.5f; input.leftY = -0.8f;
    state = controls.update(input, 0.016f, 1280, 720);
    require(state.left && state.down && !state.up && !state.right, "Left/down diagonal");
    input.leftX = -0.3f;
    require(controls.update(input, 0.016f, 1280, 720).left, "Movement hysteresis retains hold");
    input.leftX = -0.2f; input.leftY = 0;
    require(!controls.update(input, 0.016f, 1280, 720).left, "Dead zone releases movement");
    input.leftX = 0.9f; input.leftY = 0.9f;
    state = controls.update(input, 0.016f, 1280, 720);
    require(state.right && state.up && !state.left && !state.down, "Right/up diagonal");
    input.jump = input.pause = input.primary = input.interact = input.previous = input.next = true;
    state = controls.update(input, 0.016f, 1280, 720);
    require(state.jump && state.pause && state.primary && state.interact && state.previousPressed && state.nextPressed, "Held buttons and initial shoulder edges");
    state = controls.update(input, 0.016f, 1280, 720);
    require(state.jump && state.primary && state.interact && !state.previousPressed && !state.nextPressed, "Shoulders fire once while held");
    input.connected = false;
    state = controls.update(input, 0.016f, 1280, 720);
    require(!state.jump && !state.pause && !state.primary && !state.interact && !state.right && !state.up, "Disconnect releases held inputs");
    input.connected = true; input.focused = false; input.touching = true; input.touchX = 0;
    auto before = state.cursorX;
    state = controls.update(input, 0.016f, 1280, 720);
    require(!state.jump && !state.primary && !state.interact && !state.previousPressed && state.cursorX == before, "Focus loss releases buttons and ignores touch");

    Controls slow, fast;
    input = {}; input.connected = true; input.rightX = 1;
    slow.setCursor(10, 100); fast.setCursor(10, 100);
    Controls::State s, f;
    for (int i = 0; i < 60; ++i) s = slow.update(input, 1.0f / 60, 2000, 1000);
    for (int i = 0; i < 120; ++i) f = fast.update(input, 1.0f / 120, 2000, 1000);
    require(std::abs(s.cursorX - f.cursorX) < 0.02f && std::abs(s.cursorX - 1260) < 0.02f, "Frame-rate independent cursor speed");
    Controls paused;
    paused.setCursor(100, 100);
    require(paused.update(input, 10, 1280, 720).cursorX == 145, "Pause delta is capped");
    input.rightX = input.rightY = 0.08f;
    require(paused.update(input, 0.016f, 1280, 720).cursorX == 145, "Radial stick dead zone");
    input.rightX = 1; input.rightY = 1; input.touching = true; input.touchX = 0; input.touchY = 1;
    state = controls.update(input, 0.016f, 1280, 720);
    require(state.cursorX == 0 && state.cursorY == 719 && !state.primary, "Touch overrides stick, moves only, and uses bottom-left coordinates");
    input.touchX = 2; input.touchY = -1;
    state = controls.update(input, 0.016f, 1280, 720);
    require(state.cursorX == 1279 && state.cursorY == 0, "Touch clamped to display edges");
    input.touching = false; input.rightY = -1;
    state = controls.update(input, 1, 1280, 720);
    require(state.cursorX == 1279 && state.cursorY == 0, "Stick clamped to display edges");
    auto tap = [](Controls& c, Controls::Sample sample, float held) {
      sample.touching = true;
      require(!c.update(sample, 0.016f, 1280, 720).primary, "Touch down does not click");
      sample.touching = false;
      return c.update(sample, held, 1280, 720);
    };
    Controls taps;
    input = {}; input.touchX = 0.25f; input.touchY = 0.75f;
    state = tap(taps, input, 0.1f);
    require(state.primary && state.cursorX == 1279*0.25f, "Quick tap clicks on release without a controller");
    require(tap(taps, input, 0.08f).primary, "Consecutive taps each click");
    require(!taps.update(input, 0.016f, 1280, 720).primary, "Tap releases on the next frame");
    require(tap(taps, input, 0.5f).primary, "Half-second tap accepted");
    taps.update(input, 0.016f, 1280, 720);
    require(!tap(taps, input, 0.501f).primary, "Long touch does not click");
    require(!tap(taps, input, 2.0f).primary, "Frame stall cannot turn a hold into a tap");
    input.touching = true;
    taps.update(input, 0.016f, 1280, 720);
    input.touchX += 30.0f/1279;
    taps.update(input, 0.03f, 1280, 720);
    input.touchX -= 30.0f/1279;
    taps.update(input, 0.03f, 1280, 720);
    input.touching = false;
    require(!taps.update(input, 0.03f, 1280, 720).primary, "Swipe away and back stays cancelled");
    input.touching = true; taps.update(input, 0.016f, 1280, 720);
    input.touchX += 3.0f/1279; taps.update(input, 0.03f, 1280, 720);
    input.touching = false;
    require(taps.update(input, 0.03f, 1280, 720).primary, "Small contact jitter permits a tap");
    taps.update(input, 0.016f, 1280, 720);
    input.touching = true; taps.update(input, 0.016f, 1280, 720);
    input.focused = false; taps.update(input, 0.03f, 1280, 720);
    input.focused = true; taps.update(input, 0.03f, 1280, 720);
    input.touching = false;
    require(!taps.update(input, 0.03f, 1280, 720).primary, "Focus loss cancels until touch ends");
    input.touching = true; taps.update(input, 0.016f, 1280, 720);
    input.multipleTouches = true; taps.update(input, 0.03f, 1280, 720);
    input.multipleTouches = false; input.touching = false;
    require(!taps.update(input, 0.03f, 1280, 720).primary, "Multiple fingers cancel tap");
    input.touching = true; taps.update(input, 0.016f, 1280, 720);
    ++input.touchId; taps.update(input, 0.03f, 1280, 720); input.touching = false;
    require(!taps.update(input, 0.03f, 1280, 720).primary, "Finger replacement cancels tap");
    input.connected = true; input.primary = true; input.touching = true;
    require(taps.update(input, 0.016f, 1280, 720).primary, "Physical trigger stays held during touch");
    input.touching = false;
    require(taps.update(input, 0.03f, 1280, 720).primary, "Touch release does not release trigger");
    input.primary = false;
    require(!taps.update(input, 0.016f, 1280, 720).primary, "Physical trigger releases normally");
    input.rightX = 1;
    state = tap(taps, input, 0.1f);
    require(state.primary && state.cursorX == input.touchX*1279, "Stick cannot shift a tap on its release frame");
    Controls clicks;
    input = {}; input.connected = true; input.secondary = true;
    state = clicks.update(input, 0.016f, 1280, 720);
    require(state.secondary && !state.primary, "ZL/right click is independent of left click");
    require(clicks.update(input, 0.016f, 1280, 720).secondary, "Right click stays held");
    input.primary = true;
    state = clicks.update(input, 0.016f, 1280, 720);
    require(state.primary && state.secondary, "Both triggers can be held together");
    input.primary = false;
    state = clicks.update(input, 0.016f, 1280, 720);
    require(!state.primary && state.secondary, "Left release leaves right held");
    input.touching = true; clicks.update(input, 0.016f, 1280, 720);
    input.touching = false;
    state = clicks.update(input, 0.1f, 1280, 720);
    require(state.secondary && !state.primary, "Aiming by touch while right held does not tap-fire left");
    input.focused = false;
    state = clicks.update(input, 0.016f, 1280, 720);
    require(!state.primary && !state.secondary, "Focus loss releases both mouse buttons");
    input.focused = true; input.connected = false;
    require(!clicks.update(input, 0.016f, 1280, 720).secondary, "Disconnect releases right click");
    input.connected = true; input.secondary = false;
    require(!clicks.update(input, 0.016f, 1280, 720).secondary, "Right click releases normally");
    Controls hd, fullHd;
    input = {}; input.connected = true; input.rightX = 1;
    hd.setCursor(0, 0); fullHd.setCursor(0, 0);
    for(int i=0;i<60;++i){s=hd.update(input,1.0f/60,1280,720);f=fullHd.update(input,1.0f/60,1920,1080);}
    require(std::abs(f.cursorX-s.cursorX*1.5f)<0.03f,"1080p stick cursor preserves screen-relative speed");
    input = {}; input.touching = true; input.touchX = input.touchY = 1;
    state = fullHd.update(input,0.016f,1920,1080);
    require(state.cursorX==1919&&state.cursorY==1079,"1080p touch reaches top-right corner");
    input.touching = false; fullHd.update(input,0.1f,1920,1080);
    input.touching = true; input.touchX = input.touchY = 0;
    state = fullHd.update(input,0.016f,1920,1080);
    require(state.cursorX==0&&state.cursorY==0,"1080p touch reaches bottom-left corner");
    input.touchX = 10.0f/1279;
    fullHd.update(input,0.03f,1920,1080);
    input.touching = false;
    require(fullHd.update(input,0.03f,1920,1080).primary,"1080p keeps reference-space tap tolerance");
    input.touching = true; fullHd.update(input,0.016f,1920,1080);
    input.touchX += 13.0f/1279;
    fullHd.update(input,0.03f,1920,1080);input.touching=false;
    require(!fullHd.update(input,0.03f,1920,1080).primary,"1080p swiping cancels a tap");
    Controls extra;
    input = {}; input.connected = true; input.dpadLeft = input.dpadUp = true;
    state=extra.update(input,0.016f,1920,1080);
    require(state.left && state.up, "D-pad diagonal movement");
    input.leftX=-0.7f; extra.update(input,0.016f,1920,1080);
    input.dpadLeft=input.dpadUp=false;
    require(extra.update(input,0.016f,1920,1080).left,"Releasing D-pad preserves held stick movement");
    input.leftX=0; require(!extra.update(input,0.016f,1920,1080).left,"Both movement sources release");
    input.ability=true; require(extra.update(input,0.016f,1920,1080).ability,"B ability hold");
    input.ability=false; input.interact=true;
    state=extra.update(input,0.016f,1920,1080);require(state.interact&&!state.alt,"Y interacts immediately");
    state=extra.update(input,2.0f,1920,1080);require(state.interact&&!state.alt,"Exactly two seconds remains interaction");
    state=extra.update(input,0.001f,1920,1080);require(!state.interact&&state.alt,"Long Y replaces E with held Alt");
    require(extra.update(input,1.0f,1920,1080).alt,"Alt stays held");
    input.interact=false; state=extra.update(input,0.016f,1920,1080);require(!state.alt&&!state.interact,"Y release releases Alt");
    input.interact=true;extra.update(input,0.016f,1920,1080);extra.update(input,1.9f,1920,1080);
    input.focused=false;require(!extra.update(input,1,1920,1080).alt,"Focus loss releases long hold");
    input.focused=true;require(!extra.update(input,0.2f,1920,1080).alt,"Focus regain starts a fresh hold");
    input.chat=true;require(extra.update(input,0.016f,1920,1080).chatPressed,"Minus first press requests chat");
    extra.suspend();require(!extra.update(input,0.016f,1920,1080).chatPressed,"Holding Minus across keyboard cannot reopen it");
    input.chat=false;extra.update(input,0.016f,1920,1080);input.chat=true;
    require(extra.update(input,0.016f,1920,1080).chatPressed,"New Minus press requests another chat");
    input.connected=false;state=extra.update(input,3,1920,1080);
    require(!state.alt&&!state.ability&&!state.chatPressed&&!state.left&&!state.up,"Disconnect clears new controls");
    Controls precise;
    input = {}; input.connected = true; input.rightX = 0.12f;
    precise.setCursor(500, 300);
    require(precise.update(input, 0.05f, 1280, 720).cursorX == 500, "12 percent radial deadzone prevents center drift");
    input.rightX = 0.15f;
    state = precise.update(input, 0.05f, 1280, 720);
    float fine = state.cursorX - 500;
    require(fine > 0 && fine < 0.1f, "Gentle stick motion permits subpixel precision");
    precise.setCursor(500, 300); input.rightX = -0.15f;
    state = precise.update(input, 0.05f, 1280, 720);
    require(std::abs((500 - state.cursorX) - fine) < 0.001f, "Fine cursor response is symmetric");
    precise.setCursor(500, 300); input.rightX = 0.5f;
    state = precise.update(input, 0.05f, 1280, 720);
    float mid = state.cursorX - 500;
    require(mid > fine && mid < 45, "Cursor accelerates smoothly towards full stick");
    precise.setCursor(500, 300); input.rightX = 1;
    require(std::abs(precise.update(input, 0.05f, 1280, 720).cursorX - 545) < 0.001f, "Full-stick speed remains 900 pixels per second at 720p");
    input = {}; input.connected = true; input.leftY = -1;
    state = precise.update(input, 0.016f, 1280, 720);
    require(state.down && !state.shift, "Left-stick Down never presses Shift");
    input.dpadDown = true;
    state = precise.update(input, 0.016f, 1280, 720);
    require(state.down && state.shift, "D-pad Down holds both S and Left Shift");
    input.dpadDown = false;
    state = precise.update(input, 0.016f, 1280, 720);
    require(state.down && !state.shift, "D-pad release releases Shift while stick keeps S held");
    input.dpadDown = true; input.leftY = 0;
    state = precise.update(input, 0.016f, 1280, 720);
    require(state.down && state.shift, "D-pad alone holds both keys");
    input.focused = false;
    state = precise.update(input, 0.016f, 1280, 720);
    require(!state.down && !state.shift, "Focus loss releases D-pad modifier");
    input.focused = true; input.connected = false;
    require(!precise.update(input, 0.016f, 1280, 720).shift, "Disconnection releases Shift");
    input.connected = true; precise.update(input, 0.016f, 1280, 720); precise.suspend();
    input.dpadDown = false;
    require(!precise.update(input, 0.016f, 1280, 720).shift, "Applet suspension clears Shift");
    auto armMouse = [](Controls& c, Controls::Sample& sample, int width, int height) {
      sample = {}; sample.connected = true; sample.pointerActive = true; sample.pointerX = 0.01f;
      Controls::State current;
      for (int i=0; i<55; ++i) current = c.update(sample,0.02f,width,height);
      require(current.mouseMode, "One second of sustained mouse motion arms the latch");
    };
    Controls mouse;
    mouse.setCursor(500,300);
    input = {}; input.connected = true; input.pointerActive = true; input.pointerX = 10;
    for(int i=0;i<10;++i) state=mouse.update(input,0.02f,1920,1080);
    require(!state.mouseMode && state.cursorX==500,"A brief sensor brush cannot move the cursor");
    input.pointerX=0;mouse.update(input,0.2f,1920,1080);
    armMouse(mouse,input,1920,1080); mouse.setCursor(500,300);
    input.pointerX = 10; input.pointerY = -5; input.rightX = 1; input.leftX = -1;
    state = mouse.update(input, 1.0f/60, 1920, 1080);
    require(state.cursorX == 513.5f && state.cursorY == 293.25f && state.left, "Mouse is 10 percent slower while walking remains active");
    input.pointerX = input.pointerY = 0;
    state = mouse.update(input, 1.0f/60, 1920, 1080);
    require(state.mouseMode && state.cursorX == 513.5f,"A stationary latched mouse ignores a brief stick input");
    input.rightX = input.leftX = 0; input.pointerX = 100;
    input.pointerActive = false;
    require(mouse.update(input, 0.016f, 1920, 1080).cursorX == 513.5f, "Inactive pointer data ignored without dropping mode");
    input.pointerActive = true; input.focused = false;
    require(mouse.update(input, 0.016f, 1920, 1080).cursorX == 513.5f, "Unfocused mouse motion ignored");
    input.focused = true; input.connected = false;
    state=mouse.update(input, 0.016f, 1920, 1080);
    require(!state.mouseMode && state.cursorX==513.5f,"Disconnect releases mouse mode");
    armMouse(mouse,input,1920,1080);
    input.pointerX=100; input.touching = true; input.touchX = input.touchY = 0.5f;
    state = mouse.update(input, 0.016f, 1920, 1080);
    require(state.cursorX == 959.5f && state.cursorY == 539.5f, "Touch wins over Joy-Con mouse movement");
    input.touching = false;
    state = mouse.update(input, 0.1f, 1920, 1080);
    require(state.primary && state.cursorX == 959.5f, "Mouse motion cannot shift a touch tap on release");
    state = mouse.update(input, 0.016f, 1920, 1080);
    require(!state.primary && state.cursorX == 1094.5f, "Mouse resumes after touch release");
    mouse.suspend(); input.pointerActive=false;
    require(mouse.update(input,0.016f,1920,1080).mouseMode,"Keyboard suspension preserves the established mouse mode");
    input.pointerActive=true; input.pointerX = 100000; input.pointerY = -100000;
    state = mouse.update(input, 0.016f, 1920, 1080);
    require(state.cursorX == 1919 && state.cursorY == 0, "Relative mouse motion clamps to screen edges");
    Controls mouse720, mouse1080;
    armMouse(mouse720,input,1280,720);armMouse(mouse1080,input,1920,1080);
    mouse720.setCursor(0, 0); mouse1080.setCursor(0, 0);
    input.pointerX = 20; input.pointerY = 10;
    s = mouse720.update(input, 0.001f, 1280, 720);
    f = mouse1080.update(input, 0.05f, 1920, 1080);
    require(std::abs(s.cursorX-18)<0.001f && std::abs(s.cursorY-9)<0.001f && f.cursorX==27 && f.cursorY==13.5f,"Mouse sensitivity scales with resolution, not frame time");
    input.pointerX=input.pointerY=0;input.rightX=1;
    for(int i=0;i<19;++i) state=mouse1080.update(input,0.02f,1920,1080);
    require(state.mouseMode,"Stick handoff requires sustained input");
    state=mouse1080.update(input,0.02f,1920,1080);
    require(!state.mouseMode,"Sustained stick input releases mouse mode");
    mouse1080.setCursor(500,300);
    state=mouse1080.update(input,1.0f/60,1920,1080);
    require(state.cursorX==522.5f,"Full-stick speed is unchanged after mouse handoff");
    std::puts("Switch 2 controls tests passed: mappings, tap gestures, held buttons, focus/disconnect, 1080p touch bounds and resolution-independent cursor speed/tap tolerance.");
    return 0;
  } catch (std::exception const& error) {
    std::fprintf(stderr, "FAIL: %s\n", error.what());
    return 1;
  }
}
