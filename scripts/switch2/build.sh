#!/bin/sh
set -eu

: "${DEVKITPRO:?Set DEVKITPRO to your devkitPro installation}"
PROJECT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)"
BUILD_TYPE="${STAR_BUILD_TYPE:-RelWithDebInfo}"
BUILD_DIR="${STAR_BUILD_DIR:-$PROJECT_DIR/build-switch2-clean}"
export PATH="$DEVKITPRO/tools/bin:$PATH"
if [ -n "${VULKAN_SDK:-}" ]; then
    SDK_HOST_PATH="$VULKAN_SDK"
    if command -v cygpath >/dev/null 2>&1; then
        SDK_HOST_PATH="$(cygpath -u "$SDK_HOST_PATH")"
    fi
    export PATH="$SDK_HOST_PATH/Bin:$SDK_HOST_PATH/bin:$PATH"
fi
command -v glslangValidator >/dev/null 2>&1 || {
    echo "Install a host glslangValidator and add it to PATH (Windows Vulkan SDK is supported)." >&2
    exit 1
}
HOST_GLSLANG="$(command -v glslangValidator)"
if command -v cygpath >/dev/null 2>&1; then
    HOST_GLSLANG="$(cygpath -u "$HOST_GLSLANG")"
fi

cmake -S "$PROJECT_DIR" -B "$BUILD_DIR" -G Ninja \
    -DCMAKE_TOOLCHAIN_FILE="$PROJECT_DIR/cmake/toolchains/Switch2.cmake" \
    -DSTAR_GLSLANG_VALIDATOR="$HOST_GLSLANG" \
    -DCMAKE_BUILD_TYPE="$BUILD_TYPE" -DCMAKE_POLICY_VERSION_MINIMUM=3.5 \
    -DSTAR_ENABLE_VULKAN=ON -DSTAR_ENABLE_OPENGL=OFF \
    -DSTAR_RECENT_COMPILER=OFF -DSTAR_INSTALL_VCPKG=OFF \
    -DSTAR_BUILD_QT_TOOLS=OFF -DSTAR_ENABLE_STEAM_INTEGRATION=OFF \
    -DSTAR_SWITCH2_DIAGNOSTICS="${STAR_SWITCH2_DIAGNOSTICS:-OFF}" \
    -DSTAR_SWITCH2_RAM_SHIP_STORAGE="${STAR_SWITCH2_RAM_SHIP_STORAGE:-ON}" \
    -DSTAR_SWITCH2_WAIT_PROFILE="${STAR_SWITCH2_WAIT_PROFILE:-OFF}" \
    -DSTAR_SWITCH2_IO_PROFILE="${STAR_SWITCH2_IO_PROFILE:-OFF}" \
    -DSTAR_SWITCH2_ALLOCATION_PROFILE="${STAR_SWITCH2_ALLOCATION_PROFILE:-OFF}" \
    -DSTAR_SWITCH2_EXPLORATION_PROFILE="${STAR_SWITCH2_EXPLORATION_PROFILE:-OFF}" \
    -DSTAR_SWITCH2_GAMEPLAY_REGRESSION="${STAR_SWITCH2_GAMEPLAY_REGRESSION:-OFF}" \
    -DSTAR_SWITCH2_GAME_RPMALLOC="${STAR_SWITCH2_GAME_RPMALLOC:-ON}" \
    -DSTAR_SWITCH2_BOOTSTRAP_CACHE="${STAR_SWITCH2_BOOTSTRAP_CACHE:-ON}" \
    -DSTAR_SWITCH2_ASSET_STARTUP_TRACE="${STAR_SWITCH2_ASSET_STARTUP_TRACE:-OFF}" \
    -DSTAR_SWITCH2_RENDER_HEIGHT="${STAR_SWITCH2_RENDER_HEIGHT:-720}" \
    -DSTAR_ENABLE_DISCORD_INTEGRATION=OFF -DXSB_ENABLE_TRACY=OFF \
    -DSTAR_USE_JEMALLOC=OFF -DSTAR_USE_RPMALLOC=OFF -DSTAR_USE_MIMALLOC=OFF \
    -DBUILD_TESTING=OFF -DPACKAGE_XSB_ASSETS=OFF \
    -DSTAR_INSTALL_TOOLS=OFF -DSTAR_INSTALL_EXTRA_TOOLS=OFF
cmake --build "$BUILD_DIR" --target "${1:-xclient_nro}" -j "${JOBS:-4}"
